// Helper: generate 30-point trend trail with realistic noise
function genVitalsTrail(
  baseHR: number,
  baseSpO2: number,
  trend: "stable" | "deteriorating" | "improving" = "stable"
): VitalReading[] {
  return Array.from({ length: 30 }, (_, i) => {
    const factor =
      trend === "deteriorating" ? i * 0.3 :
      trend === "improving" ? -i * 0.2 : 0;
    const noise = (range: number) => (Math.random() - 0.5) * range;
    return {
      timestamp: new Date(Date.now() - (29 - i) * 60_000).toISOString(),
      heart_rate: Math.round(Math.max(40, baseHR + factor + noise(6))),
      systolic_bp: Math.round(Math.max(70, 120 + factor * 0.5 + noise(8))),
      diastolic_bp: Math.round(Math.max(50, 80 + noise(4))),
      resp_rate: Math.round(Math.max(8, 16 + factor * 0.1 + noise(2))),
      spO2: Math.min(100, Math.round(baseSpO2 - factor * 0.05 + noise(2))),
      temperature: parseFloat((37 + factor * 0.02 + noise(0.3)).toFixed(1)),
      gcs: 15,
    };
  });
}

